"""sweep_table.py: the verdict table of `cpu_tune sweep` runs over (physics schedule, projection schedule, exit choice)
configurations, against the tuned configuration and its A/A control.

  python tools/benchmark/sweep_table.py <out.md> <sweep.csv> [<sweep.csv> ...]

Per (venue, state, threads) and configuration: the median over rounds of the per-round median ms per step (total and its parts); the change
against the reference configuration (the tuned one: TUNED_SCHEDULE / TUNED_PROJECTION_SCHEDULE / the tuned exit choice, the first label without
_aa in REF below) and the A/A control's change (the same configuration under the label <choice>_aa). A configuration is faster (slower) BEYOND
NOISE when |change| > 2 x |A/A change| and the two-sided sign test over the paired rounds gives p < 0.05 (the perf protocol's rule).
"""
import csv
import math
import sys
from collections import defaultdict

REF = ("dynamic64", "dynamic64", "seq")


def sign_p(k, n):
    """Two-sided binomial sign test: P(at least max(k, n - k) of n in one direction) x 2, capped at 1."""
    if n == 0:
        return 1.0
    m = max(k, n - k)
    p = sum(math.comb(n, i) for i in range(m, n + 1)) / 2 ** n
    return min(1.0, 2 * p)


def med(v):
    v = sorted(v)
    n = len(v)
    return float("nan") if n == 0 else (v[n // 2] if n % 2 else 0.5 * (v[n // 2 - 1] + v[n // 2]))


def main():
    out, files = sys.argv[1], sys.argv[2:]
    rows, headers = [], []
    for f in files:
        with open(f, newline="") as fh:
            lines = fh.readlines()
        headers += [l.strip() for l in lines if l.startswith("#")]
        rows += list(csv.DictReader([l for l in lines if not l.startswith("#")]))
    groups = defaultdict(lambda: defaultdict(dict))   # (venue, state, threads) -> config -> round -> row
    for r in rows:
        key = (r["venue"], r["state"], int(r["threads"]))
        cfg = (r["schedule"], r["proj_schedule"], r.get("choice", "seq"))
        groups[key][cfg][int(r["round"])] = r
    md = ["# CPU schedule and exit-choice sweep", "",
          "Generated by tools/benchmark/sweep_table.py from " + ", ".join(f.replace("\\", "/") for f in files) + ".", ""]
    md += [h.lstrip("# ") for h in sorted(set(headers))]
    md += ["", "Reference: physics " + REF[0] + ", projection " + REF[1] + ", exit choice " + REF[2] + " (the tuned configuration before the parallel exit choice). "
           "Per configuration: the median over rounds of the per-round median ms per step; the change against the reference; rounds faster than the "
           "reference (paired by round); the two-sided sign test's p. **Beyond noise**: |change| > 2 x |A/A change| and p < 0.05. Parts: the exit "
           "choice (sequential or parallel), predict, the projection iterations, the final pass (medians over rounds).", ""]
    verdicts = []
    for key in sorted(groups):
        venue, state, threads = key
        cfgs = groups[key]
        if REF not in cfgs:
            continue
        ref = cfgs[REF]
        aa = next((c for c in cfgs if c[2].endswith("_aa")), None)

        def stats(cfg):
            rr = cfgs[cfg]
            common = sorted(set(rr) & set(ref))
            tot = med([float(rr[i]["total_ms"]) for i in rr])
            rtot = med([float(ref[i]["total_ms"]) for i in common])
            faster = sum(1 for i in common if float(rr[i]["total_ms"]) < float(ref[i]["total_ms"]))
            parts = {p: med([float(rr[i][p + "_ms"]) for i in rr]) for p in ("choice", "predict", "project", "final")}
            return tot, (tot - rtot) / rtot, faster, len(common), parts

        aa_change = stats(aa)[1] if aa else float("nan")
        md += [f"## venue {venue}, {state}, {threads} threads", "",
               f"Reference {stats(REF)[0]:.3f} ms per step; A/A control ({aa[2] if aa else '-'}): {100 * aa_change:+.2f}%." if aa else
               f"Reference {stats(REF)[0]:.3f} ms per step; no A/A control.", "",
               "| physics | projection | exit choice | ms per step | change | rounds faster | sign test p | verdict | choice | predict | projection | final |",
               "|---|---|---|---:|---:|---:|---:|---|---:|---:|---:|---:|"]
        ranked = sorted(cfgs, key=lambda c: stats(c)[0])
        for cfg in ranked:
            tot, ch, k, n, parts = stats(cfg)
            p = sign_p(k, n)
            if cfg == REF:
                verdict = "reference"
            elif cfg[2].endswith("_aa"):
                verdict = "A/A control"
            elif aa and abs(ch) > 2 * abs(aa_change) and p < 0.05:
                verdict = "**faster**" if ch < 0 else "**slower**"
            else:
                verdict = "within noise"
            if verdict.startswith("**"):
                verdicts.append((venue, state, threads, cfg, ch, verdict))
            md.append(f"| {cfg[0]} | {cfg[1]} | {cfg[2]} | {tot:.3f} | {100 * ch:+.2f}% | {k} / {n} | {p:.3f} | {verdict} | {parts['choice']:.3f} | "
                      f"{parts['predict']:.3f} | {parts['project']:.3f} | {parts['final']:.3f} |")
        md.append("")
    md += ["## Beyond noise (every venue / state)", ""]
    if verdicts:
        md += ["| venue | state | threads | physics / projection / exit choice | change | verdict |", "|---|---|---:|---|---:|---|"]
        for v, s, t, cfg, ch, vd in verdicts:
            md.append(f"| {v} | {s} | {t} | {cfg[0]} / {cfg[1]} / {cfg[2]} | {100 * ch:+.2f}% | {vd} |")
    else:
        md.append("None.")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(md) + "\n")
    print("\n".join(md[-(len(verdicts) + 4):]))
    print("->", out)


if __name__ == "__main__":
    main()
