"""perf_tables.py: the performance tables of results/RESULTS.md from the thesis benchmark (benchmark_crowd thesis and scaling --venue M,
results/benchmarks/thesis) and the CPU tuning sweep (results/benchmarks/cpu_tuning/sweep.md). Run from the repository root.

  python tools/figures/perf_tables.py [--out results/benchmarks/thesis/perf_tables.md]

Tables: (1) the headline per venue (S, M, L at 100% load): GPU / CPU at max threads / CPU-1 ms per step, the speedups, the real-time factors;
(2) the terrace's stress sweep with its capacity labels; (3) the GPU passes; (4) the CPU thread scaling; (5) the optimisation chain (the
historical A/B medians and this benchmark); the probe's CV and the metadata. Every value is the cells CSV's (median over rounds of the per-round
medians), p5 / p95 over every measured step.
"""
import csv
import glob
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import thesis_figures as tf  # noqa: E402

tf.LANG = "en"


def fmt(v, nd=None):
    if v is None:
        return "-"
    if nd is None:
        nd = 4 if v < 1 else 3 if v < 10 else 2 if v < 100 else 1
    return f"{v:,.{nd}f}".replace(",", " ")


def x(v):
    return "-" if v is None else (f"{v:.0f}x" if v >= 100 else f"{v:.1f}x" if v >= 10 else f"{v:.2f}x")


def main():
    out = sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else os.path.join(tf.BENCH_DIR, "perf_tables.md")
    rows, cells_file = tf.perf_rows()
    if not rows:
        sys.exit("no benchmark cells CSV (" + tf.PERF_CELLS + ")")
    run_csv = cells_file.replace("_cells.csv", ".csv")
    probes = []
    meta = {}
    if os.path.exists(run_csv):
        with open(run_csv, newline="") as f:
            for r in csv.DictReader(f):
                meta = r
                if r["impl"] == "gpu_probe":
                    probes.append(float(r["median_ms"]))
    t = tf.cpu_max(rows)
    md = ["# Performance tables", "", f"Generated by tools/figures/perf_tables.py from `{cells_file.replace(os.sep, '/')}`.", ""]
    if meta:
        md += [f"Benchmark: commit {meta['git_commit'][:7]} (dirty {meta['git_dirty']}), {meta['build']}; GPU {meta['gpu']}, driver {meta['driver']}; "
               f"clock note \"{meta['clock_note']}\"; CPU {meta['cpu']}; CPU configuration: {meta['schedule']}; {meta['qos']}; safety metrics off.", ""]
    if probes:
        mean = sum(probes) / len(probes)
        sd = (sum((p - mean) ** 2 for p in probes) / len(probes)) ** 0.5
        md += [f"Reference probe (GPU, terrace N = 4 096, spawn, 300 steps; start of each of {len(probes)} rounds): mean {mean:.4f} ms, "
               f"CV {100 * sd / mean:.2f}%.", ""]

    def c(wk, state, impl, th=0):
        return tf.pcell(rows, wk, state, impl, th)

    md += ["## (1) Constant density: venues at 100% load (the default model)", "",
           f"| venue | state | active agents (N) | GPU [ms] (p5-p95) | CPU-{t} [ms] | CPU-1 [ms] | GPU vs CPU-{t} | CPU-{t} vs CPU-1 | GPU vs CPU-1 | "
           f"real-time factor GPU / CPU-{t} / CPU-1 |", "|---|---|---:|---:|---:|---:|---:|---:|---:|---|"]
    for v in tf.PERF_VENUES:
        for state in ("spawn", "congested"):
            g, m, o = c(f"venue_{v}", state, "gpu"), c(f"venue_{v}", state, "cpu", t), c(f"venue_{v}", state, "cpu", 1)
            if not g:
                continue
            gm, mm, om = g["round_median_ms"], m["round_median_ms"] if m else None, o["round_median_ms"] if o else None
            rt = " / ".join(fmt(tf.DT_REAL_MS / q, 1 if tf.DT_REAL_MS / q < 10 else 0) + "x" if q else "-" for q in (gm, mm, om))
            md.append(f"| {v} | {state} | {g['agents']:,} ({g['N']:,}) | {fmt(gm)} ({fmt(g['p5_ms'])}-{fmt(g['p95_ms'])}) | {fmt(mm)} | {fmt(om)} | "
                      f"{x(mm / gm) if mm else '-'} | {x(om / mm) if om and mm else '-'} | {x(om / gm) if om else '-'} | {rt} |".replace(",", " "))
    md += ["", f"CPU-1 rounds and steps per row: the cells CSV (`rounds`, `measured_steps`); CPU-1 at L: 5 steps in 3 rounds.", ""]
    md += ["## (2) Fixed-venue stress sweep: the terrace", "",
           f"| N | state | GPU [ms] (p5-p95) | CPU-{t} [ms] | CPU-1 [ms] | GPU vs CPU-{t} | CPU-{t} vs CPU-1 | real-time factor GPU | capacity label |",
           "|---:|---|---:|---:|---:|---:|---:|---:|---|"]
    for n in tf.TERRACE_NS:
        for state in ("spawn", "congested"):
            g, m, o = c(f"terrace_{n}", state, "gpu"), c(f"terrace_{n}", state, "cpu", t), c(f"terrace_{n}", state, "cpu", 1)
            if not g:
                continue
            gm, mm, om = g["round_median_ms"], m["round_median_ms"] if m else None, o["round_median_ms"] if o else None
            md.append(f"| {n:,} | {state} | {fmt(gm)} ({fmt(g['p5_ms'])}-{fmt(g['p95_ms'])}) | {fmt(mm)} | {fmt(om)} | {x(mm / gm) if mm else '-'} | "
                      f"{x(om / mm) if om and mm else '-'} | {fmt(tf.DT_REAL_MS / gm, 0)}x | {g['label']} |".replace(",", " ", 1))
    md += ["", "## (3) GPU passes (ms; median over rounds)", "",
           "| workload | state | hash | sort | cells / gather | exit choice | predict | projection | final | total | projection share | projection + final |",
           "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for wk in [f"venue_{v}" for v in tf.PERF_VENUES] + [f"terrace_{n}" for n in tf.TERRACE_NS]:
        for state in ("spawn", "congested"):
            g = c(wk, state, "gpu")
            if not g:
                continue
            tot = g["round_median_ms"]
            md.append(f"| {wk} | {state} | " + " | ".join(fmt(g[p + '_ms']) for p in tf.PASSES) + f" | {fmt(tot)} | {100 * g['project_ms'] / tot:.0f}% | "
                      f"{100 * (g['project_ms'] + g['final_ms']) / tot:.0f}% |")
    md += ["", f"## CPU stages (CPU-{t} and CPU-1, ms)", "",
           "| workload | state | threads | hash | sort | cells | exit choice | predict | projection | final | total |", "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for wk in [f"venue_{v}" for v in tf.PERF_VENUES] + [f"terrace_{n}" for n in tf.TERRACE_NS]:
        for state in ("spawn", "congested"):
            for th in (t, 1):
                g = c(wk, state, "cpu", th)
                if g:
                    md.append(f"| {wk} | {state} | {th} | " + " | ".join(fmt(g[p + '_ms']) for p in tf.PASSES) + f" | {fmt(g['round_median_ms'])} |")
    srows, sfile = tf.scaling_rows()
    if srows:
        by = {}
        for r in srows:
            by.setdefault(int(r["threads"]), []).append(float(r["median_ms"]))
        med = {k: sorted(v)[len(v) // 2] for k, v in by.items()}
        md += ["", f"## (4) CPU thread scaling: venue {srows[0]['venue']} at 100%, congested (`{sfile.replace(os.sep, '/')}`)", "",
               "| threads | ms per step (median of 3 rounds) | speedup vs 1 | efficiency |", "|---:|---:|---:|---:|"]
        for k in sorted(med):
            md.append(f"| {k} | {fmt(med[k])} | {med[1] / med[k]:.2f}x | {100 * med[1] / med[k] / k:.0f}% |")
    md += ["", "## (5) The optimisation chain: GPU ms per step, the terrace (spawn / congested)", "",
           "Historical rows: the A/B medians of their changes (AMD 26.8.1, snapshot mode; the first four the point / disk model before the hard bodies): "
           + ", ".join(tf.CHAIN_SOURCES) + ". The last row: this benchmark (AMD 26.10.1, the current model).", "",
           "| step | model and driver | N = 4 096 | N = 65 536 | N = 262 144 |", "|---|---|---:|---:|---:|"]
    what = {"host": ("Buffers GL_DYNAMIC_DRAW (host memory from 4 MB)", "historical model and driver"),
            "vram": ("GL_DYNAMIC_COPY (VRAM)", "historical model and driver"),
            "sort": ("Bitonic passes j < 512 in shared memory", "historical model and driver"),
            "gather": ("Sorted state gather", "historical model and driver"),
            "hardbody": ("Hard bodies, headway model, projection K = 32", "hard-body model, historical driver")}
    for k, vals in tf.CHAIN:
        cellsx = [f"{fmt(vals[n][0])} / {fmt(vals[n][1])}" if n in vals else "-" for n in (4096, 65536, 262144)]
        md.append(f"| {what[k][0]} | {what[k][1]} | " + " | ".join(cellsx) + " |")
    cur = []
    for n in (4096, 65536, 262144):
        s, g = c(f"terrace_{n}", "spawn", "gpu"), c(f"terrace_{n}", "congested", "gpu")
        cur.append(f"{fmt(s['round_median_ms'])} / {fmt(g['round_median_ms'])}" if s and g else "-")
    md.append("| The current model (step-up limit, the venues' code paths) | current model, AMD 26.10.1 | " + " | ".join(cur) + " |")
    sweep = "results/benchmarks/cpu_tuning/sweep.md"
    if os.path.exists(sweep):
        md += ["", f"CPU tuning verdicts: `{sweep}`."]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(md) + "\n")
    print("\n".join(md))
    print("->", out)


if __name__ == "__main__":
    main()
